"""Generate IFC schema metadata TSV tables for CheckMate's pure-Java STEP reader.

Reads the IFC2X3, IFC4 and IFC4X3_ADD2 schemas from IfcOpenShell's EXPRESS schema
definitions and writes compact tab-separated tables under
``src/main/resources/ifc/schema/{ifc2x3,ifc4,ifc4x3}.tsv``.

Usage (from this folder, with IfcOpenShell installed):

    python generate_ifc_schemas.py ../resources/ifc/schema

Each output file contains:
- ``#`` comment header lines with the source schema name and column format.
- ``E`` rows for every entity declaration:
  ``E\tUPPER\tCanonical\tSupertypeUpperOrEmpty\tisObject\tisTypeObject\tpredefinedTypeSlot\telementTypeSlot\tprocessTypeSlot``
- ``T`` rows for every non-entity declaration (defined types, enumerations, selects):
  ``T\tUPPER\tCanonical``
"""

import pathlib
import sys

import ifcopenshell.ifcopenshell_wrapper as ifc_wrapper

SCHEMAS = (
    ("IFC2X3", "ifc2x3.tsv"),
    ("IFC4", "ifc4.tsv"),
    ("IFC4X3_ADD2", "ifc4x3.tsv"),
)


def is_subtype_of(entity, target_name):
    """Return True if ``entity`` is ``target_name`` or inherits from it."""
    current = entity
    while current is not None:
        if current.name() == target_name:
            return True
        current = current.supertype()
    return False


def attribute_slot(attr_names, name):
    """Return the 0-based index of ``name`` in ``attr_names``, or -1 if absent."""
    try:
        return attr_names.index(name)
    except ValueError:
        return -1


def write_schema(schema_name, output_path):
    schema = ifc_wrapper.schema_by_name(schema_name)
    entity_rows = []
    type_rows = []

    for declaration in schema.declarations():
        canonical = declaration.name()
        upper = canonical.upper()
        entity = declaration.as_entity()
        if entity is not None:
            supertype = entity.supertype()
            supertype_upper = supertype.name().upper() if supertype is not None else ""
            is_object = 1 if is_subtype_of(entity, "IfcObject") else 0
            is_type_object = 1 if is_subtype_of(entity, "IfcTypeObject") else 0
            attr_names = [attr.name() for attr in entity.all_attributes()]
            predefined_slot = attribute_slot(attr_names, "PredefinedType")
            element_type_slot = attribute_slot(attr_names, "ElementType")
            process_type_slot = attribute_slot(attr_names, "ProcessType")
            entity_rows.append(
                (
                    upper,
                    f"E\t{upper}\t{canonical}\t{supertype_upper}\t{is_object}\t"
                    f"{is_type_object}\t{predefined_slot}\t{element_type_slot}\t{process_type_slot}",
                )
            )
        else:
            type_rows.append((upper, f"T\t{upper}\t{canonical}"))

    entity_rows.sort(key=lambda item: item[0])
    type_rows.sort(key=lambda item: item[0])

    output_path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        f"# Source schema: {schema_name} (generated by generate_ifc_schemas.py)",
        "# E\tUPPER\tCanonical\tSupertypeUpper\tisObject\tisTypeObject\tpredefinedTypeSlot\telementTypeSlot\tprocessTypeSlot",
        "# T\tUPPER\tCanonical",
        *(row for _, row in entity_rows),
        *(row for _, row in type_rows),
    ]
    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(entity_rows), len(type_rows)


def main():
    default_out = pathlib.Path(__file__).resolve().parents[1] / "resources" / "ifc" / "schema"
    out_dir = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else default_out
    for schema_name, filename in SCHEMAS:
        target = out_dir / filename
        entities, types = write_schema(schema_name, target)
        print(f"written {target} ({schema_name}: {entities} entities, {types} types)")


if __name__ == "__main__":
    main()
